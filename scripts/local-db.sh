#!/bin/bash
# A local Supabase built from supabase/migrations, for the RLS tests and for trying a migration
# before it reaches the hosted project. Docker comes from Colima on this Mac (brew install colima
# docker); CI starts the same stack on GitHub's Docker.
#
#   npm run db:start    start Colima if needed, then Supabase without the parts nothing here uses
#   npm run db:test     the pgTAP tests in supabase/tests (starts the stack first)
#   npm run db:reset    rebuild the database from the migrations
#   npm run db:types    write src/lib/database.types.ts from the local database (CI checks it matches)
#   npm run db:stop     stop Supabase, then Colima
set -euo pipefail
cd "$(dirname "$0")/.."

# The services CI leaves out too (.github/workflows/ci.yml). Auth and Storage stay: the tests use them.
EXCLUDE=realtime,imgproxy,mailpit,postgres-meta,studio,edge-runtime,logflare,vector,supavisor

docker_up() {
  if [ -z "${DOCKER_HOST:-}" ] && command -v colima >/dev/null; then
    colima status >/dev/null 2>&1 || colima start --cpu 4 --memory 6 --vm-type vz --mount-type virtiofs
    export DOCKER_HOST="unix://$HOME/.colima/default/docker.sock"
  fi
  docker info >/dev/null 2>&1 || { echo "No Docker: brew install colima docker, then run this again."; exit 1; }
}

case "${1:-}" in
  start) docker_up; supabase start -x "$EXCLUDE" ;;
  test) docker_up; supabase status >/dev/null 2>&1 || supabase start -x "$EXCLUDE"; supabase test db --local ;;
  types)
    docker_up
    supabase status >/dev/null 2>&1 || supabase start -x "$EXCLUDE"
    { echo "// Generated by npm run db:types from the local database built from supabase/migrations. Don't edit."
      supabase gen types typescript --local --schema public
    } | npx -y prettier@3.3.3 --stdin-filepath src/lib/database.types.ts --print-width 110 > src/lib/database.types.ts
    ;;
  reset) docker_up; supabase db reset --local ;;
  stop) docker_up; supabase stop; command -v colima >/dev/null && colima stop ;;
  *) echo "usage: $0 start|test|reset|stop"; exit 1 ;;
esac
