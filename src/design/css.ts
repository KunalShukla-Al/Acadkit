/**
 * The themes' tokens (tokens.json) as CSS: one block of custom properties
 * per theme and mode, [data-theme='x'] and [data-theme='x'].dark, which the
 * stylesheet reads as hsl(var(--bg)) and so on. npm run tokens writes it to
 * tokens.css; a test fails when that file is out of date.
 */
import { hslToHex } from "./color.ts";

export type Mode = "light" | "dark";
/** A theme: its tokens in each mode, and one line on what it is. */
export type ThemeTokens = Record<Mode, Record<string, string>> & { $about?: string };
export interface Tokens {
  themes: Record<string, ThemeTokens>;
}

/** "{accent}" is another token, as a var(); anything else is the value itself. */
const value = (v: string) => v.replace(/\{([\w-]+)\}/g, "var(--$1)");

export function tokensCss(tokens: Tokens): string {
  const blocks = Object.entries(tokens.themes).flatMap(([name, modes]) => [
    ...(modes.$about ? [`  /* ${name}: ${modes.$about} */`] : []),
    ...(["light", "dark"] as const).map((mode) => {
      const selector = `[data-theme='${name}']${mode === "dark" ? ".dark" : ""}`;
      const props = Object.entries(modes[mode]).map(([k, v]) => `    --${k}: ${value(v)};`);
      return `  ${selector} {\n${props.join("\n")}\n  }`;
    }),
  ]);
  return `/* Generated by npm run tokens from src/design/tokens.json. Don't edit. */\n@layer utilities {\n${blocks.join("\n")}\n}\n`;
}

/** A token's own value, with "{x}" followed to the token it names. */
export function resolve(modeTokens: Record<string, string>, key: string): string {
  const v = modeTokens[key];
  const ref = /^\{([\w-]+)\}$/.exec(v ?? "");
  return ref ? resolve(modeTokens, ref[1]) : v;
}

/** Each theme and mode's background as hex, "brutalist-dark": "#0a0a0a", for the browser's theme-color. */
export function backgrounds(tokens: Tokens): Record<string, string> {
  return Object.fromEntries(
    Object.entries(tokens.themes).flatMap(([name, modes]) =>
      (["light", "dark"] as const).map((mode) => [`${name}-${mode}`, hslToHex(resolve(modes[mode], "bg"))])
    )
  );
}
